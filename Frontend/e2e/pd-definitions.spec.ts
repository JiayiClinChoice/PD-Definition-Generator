import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import ExcelJS from 'exceljs';
import { acceptConfirmation, mockWorkspace } from './fixtures';

test('facts and definitions are editable, persistent and exportable', async ({ page }) => {
  await mockWorkspace(page);
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /方案事实抽取/ }).click();
  await page.getByLabel('事实内容', { exact: true }).fill('修订后的方案事实');
  await page.getByLabel('来源', { exact: true }).fill('第 9 页');
  await page.getByRole('button', { name: '保存事实修改', exact: true }).click();
  await expect(page.locator('.workspace:not([hidden]) .operation-notice')).toContainText('修改已保存');
  await page.reload();
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /方案事实抽取/ }).click();
  await expect(page.getByLabel('事实内容', { exact: true })).toHaveValue('修订后的方案事实');
  await page.getByRole('button', { name: /PD 定义生成/ }).click();
  await page.getByLabel('方案偏离的具体描述', { exact: true }).fill('=HYPERLINK("https://example.invalid")');
  await page.getByLabel('备注', { exact: true }).fill('第一行\n第二行，含逗号');
  await expect(page.getByRole('button', { name: '导出 Excel', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '保存定义修改', exact: true }).click();
  await expect(page.locator('.workspace:not([hidden]) .operation-notice')).toContainText('修改已保存');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 Excel', exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('PD-definitions-1.xlsx');
  const file = await download.path();
  expect(file).not.toBeNull();
  const bytes = await readFile(file!);
  expect(bytes.subarray(0, 2).toString()).toBe('PK');
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile(file!);
  const sheet = workbook.getWorksheet('PD 定义')!;
  expect(sheet.getCell('E2').value).toBe('=HYPERLINK("https://example.invalid")');
  expect(sheet.getCell('E2').type).toBe(ExcelJS.ValueType.String);
  expect(sheet.getCell('H2').text).toBe('第一行\n第二行，含逗号');
  expect(sheet.getCell('I1').text).toBe('方案版本');
  expect(sheet.getCell('I2').text).toBe('V1.0 / 2026-11-11');
  expect(workbook.worksheets).toHaveLength(1);
  expect(sheet.views[0].state).toBe('frozen');
  await page.reload();
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /PD 定义生成/ }).click();
  await expect(page.getByLabel('备注', { exact: true })).toHaveValue('第一行\n第二行，含逗号');
  await page.getByLabel('搜索结果', { exact: true }).fill('不存在内容');
  await expect(page.getByText('没有匹配的结果。')).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('generation is explicit and failures preserve editable results', async ({ page }) => {
  await mockWorkspace(page);
  await page.route('**/api/project/1/extract_facts', (route) => route.fulfill({ status: 502, json: { detail: 'AI 暂不可用' } }));
  await page.goto('/');
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /方案事实抽取/ }).click();
  await page.locator('.ai-panel summary').click();
  await page.getByRole('button', { name: '提取事实', exact: true }).click();
  await acceptConfirmation(page, '继续替换');
  await expect(page.getByRole('alert')).toContainText('AI 暂不可用');
  await expect(page.getByLabel('事实内容', { exact: true })).toHaveValue('研究程序前签署知情同意书');
  await expect(page.getByRole('button', { name: '提取事实', exact: true })).toBeEnabled();
});

test('facts and definitions can also be added manually', async ({ page }) => {
  const data = await mockWorkspace(page);
  await page.goto('/');
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /方案事实抽取/ }).click();
  await page.getByRole('button', { name: '添加事实', exact: true }).click();
  await page.getByLabel('事实内容', { exact: true }).last().fill('手动补充的事实');
  await page.getByRole('button', { name: '保存事实修改', exact: true }).click();
  await expect(page.locator('.workspace:not([hidden]) .operation-notice')).toContainText('修改已保存');
  expect(data().facts).toHaveLength(2);
  await page.getByRole('button', { name: /PD 定义生成/ }).click();
  await page.getByRole('button', { name: '添加定义', exact: true }).click();
  await page.getByLabel('方案偏离编号', { exact: true }).last().fill('1.02');
  await page.getByLabel('方案偏离的具体描述', { exact: true }).last().fill('手动补充的偏离定义');
  await page.getByLabel('方案中的标准', { exact: true }).last().fill('手动补充标准');
  await page.getByRole('button', { name: '保存定义修改', exact: true }).click();
  await expect(page.locator('.workspace:not([hidden]) .operation-notice')).toContainText('修改已保存');
  expect(data().definitions).toHaveLength(2);
});
