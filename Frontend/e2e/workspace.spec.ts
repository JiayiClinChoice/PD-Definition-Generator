import { test, expect } from '@playwright/test';
import { acceptConfirmation, mockWorkspace } from './fixtures';

test('categories are edited, reordered, saved and restored without JSON', async ({ page }) => {
  const data = await mockWorkspace(page);
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await expect(page.getByLabel('方案编号', { exact: true })).toHaveValue('ABC-001');
  await page.getByRole('button', { name: /PD 分类/ }).click();
  await expect(page.getByLabel('分类名称')).toHaveCount(2);
  await page.getByLabel('分类名称').first().fill('知情同意与权益');
  await page.getByRole('button', { name: '添加分类', exact: true }).click();
  await page.getByLabel('分类名称').last().fill('访视');
  await page.locator('.row-details summary').last().click();
  await page.getByLabel('分类描述').last().fill('研究访视要求');
  await page.getByLabel('提取方法').last().fill('按访视总结');
  await page.getByRole('button', { name: '拖动分类 3', exact: true }).focus();
  await page.keyboard.press('Space');
  await expect(page.getByRole('button', { name: '拖动分类 3', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.keyboard.press('ArrowUp');
  await expect.poll(() => page.locator('.dragging').evaluate((node) => new DOMMatrix(getComputedStyle(node).transform).m42)).not.toBe(0);
  await page.keyboard.press('Space');
  await expect(page.getByLabel('分类名称').nth(1)).toHaveValue('访视');
  await page.getByRole('button', { name: '保存分类配置', exact: true }).click();
  await acceptConfirmation(page, '保存并清空事实');
  await expect(page.locator('.workspace:not([hidden]) .operation-notice')).toContainText('分类已保存');
  expect(data().facts).toEqual([]);
  expect(data().categories.map((item) => item.ord)).toEqual([1, 2, 3]);
  await page.reload();
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /PD 分类/ }).click();
  await expect(page.getByLabel('分类名称').first()).toHaveValue('知情同意与权益');
  await expect(page.getByLabel('分类名称').nth(1)).toHaveValue('访视');
  await page.getByRole('button', { name: '删除分类 3', exact: true }).click();
  await acceptConfirmation(page, '删除');
  await page.getByRole('button', { name: '保存分类配置', exact: true }).click();
  await expect(page.getByLabel('分类名称')).toHaveCount(2);
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('field changes persist rather than silently resetting defaults', async ({ page }) => {
  const data = await mockWorkspace(page);
  await page.goto('/');
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /字段协议/ }).click();
  const field = page.locator('.field-row').filter({ has: page.locator('summary', { hasText: '严重程度' }) });
  await field.locator('summary').click();
  await field.getByLabel('字段含义', { exact: true }).fill('新的严重程度判断规则');
  await field.getByLabel('允许值（每行一个，不限制时留空）', { exact: true }).fill('重要\n非重要\nTBD');
  await field.getByLabel('生成要求', { exact: true }).fill('根据安全性影响判断');
  await field.getByLabel('示例（每行一个）', { exact: true }).fill('重要\nTBD');
  await page.getByRole('button', { name: '保存字段规则', exact: true }).click();
  await expect(page.locator('.workspace:not([hidden]) .operation-notice')).toContainText('字段规则已保存');
  expect(data().fields.find((item) => item.name === 'severity')?.allowed_values).toEqual(['重要', '非重要', 'TBD']);
  await page.reload();
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /字段协议/ }).click();
  await field.locator('summary').click();
  await expect(field.getByLabel('字段含义', { exact: true })).toHaveValue('新的严重程度判断规则');
  await expect(field.getByLabel('允许值（每行一个，不限制时留空）', { exact: true })).toHaveValue('重要\n非重要\nTBD');
});

test('switching projects warns on unsaved data and never carries drafts across projects', async ({ page }) => {
  await mockWorkspace(page);
  await page.goto('/');
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /PD 分类/ }).click();
  await page.getByLabel('分类名称').first().fill('未保存分类');
  await page.getByRole('button', { name: '返回项目列表', exact: true }).click();
  await acceptConfirmation(page, '取消');
  if (await page.getByRole('heading', { name: '项目', exact: true }).isVisible()) await page.getByRole('button', { name: /^第二个项目/ }).click();
  await expect(page.getByLabel('分类名称').first()).toHaveValue('未保存分类');
  await page.getByRole('button', { name: '返回项目列表', exact: true }).click();
  await acceptConfirmation(page, '放弃修改');
  if (await page.getByRole('heading', { name: '项目', exact: true }).isVisible()) await page.getByRole('button', { name: /^第二个项目/ }).click();
  await expect(page.getByRole('heading', { name: '第二个项目', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /PD 分类/ }).click();
  await expect(page.getByLabel('分类名称')).toHaveCount(1);
  await expect(page.getByLabel('分类名称')).toHaveValue('独立分类');
  await page.getByRole('button', { name: '返回项目列表', exact: true }).click();
  await page.getByRole('button', { name: /^ABC-001 临床研究/ }).click();
  await page.getByRole('button', { name: /PD 分类/ }).click();
  await expect(page.getByLabel('分类名称').first()).toHaveValue('知情同意');
});
